"""Exercise HTTPS, internal permissions and mTLS leaf rotation on synthetic accounts.

Requires the workspace generated by configure-auth-https.py. Original users are never read.
Traffic continues during validation, activation, graceful reload and automatic rollback.
"""
import argparse
import copy
from http.cookiejar import CookieJar
import importlib.util
import json
from pathlib import Path
import secrets
import subprocess
import threading
import time
import urllib.error
import urllib.parse
import urllib.request
import ssl
import hashlib
import hmac


def load_module(filename, name):
    specification = importlib.util.spec_from_file_location(name, Path(__file__).with_name(filename))
    module = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(module)
    return module


setup = load_module('configure-auth-https.py', 'https_setup')
rotation = load_module('rotate-mtls-certificate.py', 'mtls_rotation')


def docker(*arguments, body=None, check=True):
    return subprocess.run(['docker', *arguments], input=body, capture_output=True, check=check, timeout=30)


def service_metadata(project, identity):
    metadata = json.loads(docker('inspect', project+'-'+identity+'-1').stdout)[0]
    if metadata['Config']['Labels'].get('com.docker.compose.project') != project:
        raise ValueError('Unexpected Docker project')
    return metadata


def run(workspace, accounts_file):
    manifest = json.loads((workspace/'rotation.json').read_text())
    project = manifest['project']
    if not project.startswith('vicartech-auth-e2e-'):
        raise ValueError('Only an isolated validation stack is accepted')
    metadata = {identity:service_metadata(project, identity) for identity in ['gateway','auth-service','clients-service','appointments-service','database']}
    report = {'project':project, 'checks':[], 'traffic':{'successes':0,'failures':[]}}
    def passed(name):
        report['checks'].append({'name':name,'status':'passed'})
    accounts = json.loads(accounts_file.read_text())['accounts']
    jar = CookieJar()
    context = ssl.create_default_context(cafile=str(workspace/'authority/cert.pem'))
    client = urllib.request.build_opener(urllib.request.HTTPSHandler(context=context), urllib.request.HTTPCookieProcessor(jar))
    def request(path, method='GET', body=None, csrf=False, headers=None):
        request_headers = {'Accept':'application/json', 'Origin':'https://localhost:5443', **(headers or {})}
        if body is not None:
            request_headers['Content-Type']='application/json'
        if csrf:
            request_headers['X-XSRF-TOKEN'] = urllib.parse.unquote(next(cookie.value for cookie in jar if cookie.name == 'XSRF-TOKEN'))
        request = urllib.request.Request('https://localhost:5443'+path, data=body, method=method, headers=request_headers)
        try:
            response = client.open(request, timeout=8)
        except urllib.error.HTTPError as response:
            return response.code, response.read()
        with response:
            return response.status, response.read()
    assert request('/sanctum/csrf-cookie')[0] == 204
    account = accounts[0]
    assert request('/login','POST',json.dumps({'email':account['email'],'password':account['password']}).encode(),csrf=True)[0] == 204
    status, body = request('/api/user',headers={'X-User-ID':'999'})
    subject = str(json.loads(body)['id'])
    assert status == 200 and subject != '999'
    passed('Verified local HTTPS login and public identity-header spoofing rejection')
    session = next(cookie.value for cookie in jar if cookie.name == 'vicartech-auth-session')
    csrf = urllib.parse.unquote(next(cookie.value for cookie in jar if cookie.name == 'XSRF-TOKEN'))
    def internal(identity='clients-service', permission='clients.read', method='GET', token=None, cookie=True, certificate=True, wrong_ca=False, signature_headers=None):
        config = dict(entry.split('=',1) for entry in metadata[identity]['Config']['Env'])
        key_mount = next(mount for mount in metadata[identity]['Mounts'] if mount['Destination'] == config['AUTH_SIGNING_KEY_FILE'])
        key = Path(key_mount['Source']).read_bytes()
        target = '/api/internal/v1/session/validate'
        payload = b''
        if method == 'GET':
            target += '?permission='+urllib.parse.quote(permission)
        else:
            payload = json.dumps({'permission':permission},separators=(',',':')).encode()
        timestamp = str(int(time.time())); nonce = secrets.token_urlsafe(24)
        canonical = '\n'.join([method,target,timestamp,nonce,hashlib.sha256(payload).hexdigest()])
        headers = signature_headers or {'X-Internal-Service':identity,'X-Internal-Timestamp':timestamp,'X-Internal-Nonce':nonce,'X-Internal-Signature':hmac.new(key,canonical.encode(),hashlib.sha256).hexdigest()}
        headers = {**headers,'Accept':'application/json','X-User-ID':'999'}
        if cookie: headers['Cookie']='vicartech-auth-session='+session
        if token: headers['X-XSRF-TOKEN']=token
        options = ['silent','show-error','max-time = 5','url = '+json.dumps('https://auth-service:8443'+target),'request = '+json.dumps(method),'cacert = '+json.dumps('/run/vicartech-tls/current/cert.pem' if wrong_ca else '/run/vicartech-tls/current/ca.pem'),'write-out = "\\n%{http_code}"']
        if certificate:
            options += ['cert = "/run/vicartech-tls/current/cert.pem"','key = "/run/vicartech-tls/current/key.pem"']
        for name, value in headers.items(): options.append('header = '+json.dumps(name+': '+value))
        if method == 'POST':
            options += ['header = "Content-Type: application/json"','data = '+json.dumps(payload.decode())]
        result = docker('exec','-i',project+'-'+identity+'-1','curl','--config','-',body=('\n'.join(options)+'\n').encode(),check=False)
        if result.returncode: return 0, {}, headers
        content, status = result.stdout.rsplit(b'\n',1)
        return int(status), json.loads(content) if content.startswith(b'{') else {}, headers
    def adapter(identity='clients-service'):
        options = ['silent','show-error','max-time = 5',
                   'url = "http://127.0.0.1:8080/api/internal/identity-check"',
                   'header = "Accept: application/json"',
                   'header = "X-User-ID: 999"',
                   'header = '+json.dumps('Cookie: vicartech-auth-session='+session),
                   'write-out = "\\n%{http_code}"']
        result = docker('exec','-i',project+'-'+identity+'-1','curl','--config','-',body=('\n'.join(options)+'\n').encode(),check=False)
        if result.returncode: return 0, {}
        content, status = result.stdout.rsplit(b'\n',1)
        return int(status),json.loads(content)
    status, payload, signed = internal()
    assert status == 200 and payload['subject'] == subject
    assert internal(signature_headers=signed)[0] == 401
    assert internal(cookie=False)[0] == 401
    assert internal(permission='appointments.read')[0] == 403
    assert internal(permission='clients.write')[0] == 403
    assert internal(method='POST',permission='clients.write')[0] == 419
    assert internal(method='POST',permission='clients.write',token='invalid')[0] == 419
    assert internal(method='POST',permission='clients.write',token=csrf)[0] == 200
    assert internal(identity='appointments-service',permission='appointments.read')[0] == 200
    assert internal(certificate=False)[0] != 200
    assert internal(wrong_ca=True)[0] == 0
    passed('mTLS, HMAC, replay, absent session, service scopes and mandatory write CSRF')
    assert request('/api/internal/v1/session/validate')[0] == 404
    passed('Internal identity endpoints remain unpublished')
    stop = threading.Event()
    def traffic():
        while not stop.is_set():
            try:
                status, _ = request('/api/user')
                if status != 200: report['traffic']['failures'].append({'path':'/api/user','status':status})
                else: report['traffic']['successes'] += 1
                status, payload = adapter()
                if status != 200 or payload.get('subject') != subject: report['traffic']['failures'].append({'path':'remote-adapter','status':status})
                else: report['traffic']['successes'] += 1
            except Exception as exception:
                report['traffic']['failures'].append({'exception':type(exception).__name__})
            stop.wait(.5)
    worker = threading.Thread(target=traffic)
    worker.start()
    run_name = secrets.token_hex(4)
    tls_directory = Path(manifest['tls_directory'])
    try:
        for identity in ['clients-service','appointments-service','gateway','auth-service']:
            candidate = tls_directory/identity/'releases'/('renewed-'+run_name)
            prepared = rotation.prepare_release(manifest,identity,candidate.name)
            assert prepared['activated'] is False
            setup.openssl('x509','-req','-in',candidate/'request.pem','-CA',workspace/'authority/cert.pem','-CAkey',workspace/'authority/key.pem','-set_serial','0x'+secrets.token_hex(16),'-days','90','-copy_extensions','copy','-out',candidate/'cert.pem')
            result = rotation.rotate(manifest,identity,candidate.name)
            assert result['activeRelease'] == candidate.name
            assert internal(identity='appointments-service',permission='appointments.read')[0] == 200
            for consumer in ['clients-service','appointments-service']:
                status, payload = adapter(consumer)
                assert status == 200 and payload['subject'] == subject
            assert request('/api/user')[0] == 200
            passed(identity+': issued certificate activated without a container restart')
        # Verify the server actually presents the new serial on a fresh verified TLS connection.
        peer = docker('exec','-i',project+'-clients-service-1','openssl','s_client','-connect','auth-service:8443','-servername','auth-service','-verify_hostname','auth-service','-verify_return_error','-CAfile','/run/vicartech-tls/current/ca.pem','-cert','/run/vicartech-tls/current/cert.pem','-key','/run/vicartech-tls/current/key.pem','-showcerts',body=b'').stdout
        observed = subprocess.run(['openssl','x509','-noout','-serial'],input=peer,capture_output=True,check=True).stdout
        expected = setup.openssl('x509','-in',tls_directory/'auth-service/current/cert.pem','-noout','-serial')
        assert observed == expected
        passed('Fresh mTLS connection observes the renewed Auth server certificate')
        # Rejected candidates never alter the current link or serving workers.
        for case in ['wrong-identity','expired','wrong-key','wrong-server-name']:
            identity = 'auth-service' if case == 'wrong-server-name' else 'gateway'
            root = tls_directory/identity
            before = (root/'current').resolve()
            candidate = root/'releases'/(case+'-'+run_name)
            setup.issue_certificate(workspace/'authority',candidate,'unknown-caller' if case == 'wrong-identity' else identity,'DNS:wrong-service' if case == 'wrong-server-name' else None,days=0 if case == 'expired' else 90)
            if case == 'wrong-key':
                (candidate/'key.pem').write_bytes((root/'releases/initial/key.pem').read_bytes())
            try:
                rotation.rotate(manifest,identity,candidate.name)
            except (ValueError,RuntimeError): pass
            else: raise AssertionError('Invalid certificate accepted: '+case)
            assert (root/'current').resolve() == before
            passed('Unsafe certificate rejected before activation: '+case)
        # Real reload followed by a failed one-shot health gate must restore the old release.
        root = tls_directory/'gateway'; before = (root/'current').resolve()
        candidate = root/'releases'/('rollback-'+run_name)
        setup.issue_certificate(workspace/'authority',candidate,'gateway')
        marker = workspace/('health-failure-'+run_name)
        temporary_manifest = copy.deepcopy(manifest)
        health_code = 'import pathlib,subprocess,sys; marker=pathlib.Path(sys.argv[1]); first=not marker.exists(); marker.touch(); sys.exit(1 if first else subprocess.run(sys.argv[2:]).returncode)'
        temporary_manifest['health_commands']['gateway'] = ['python3','-c',health_code,str(marker),*manifest['health_commands']['gateway']]
        try: rotation.rotate(temporary_manifest,'gateway',candidate.name)
        except RuntimeError: pass
        else: raise AssertionError('A failed health gate did not reject activation')
        assert (root/'current').resolve() == before
        assert request('/api/user')[0] == 200
        passed('Real graceful reload with failed health gate restores the previous certificate')
        for identity in ['gateway','auth-service','clients-service','appointments-service']:
            current = service_metadata(project,identity)
            assert current['State']['StartedAt'] == metadata[identity]['State']['StartedAt']
            assert current['RestartCount'] == metadata[identity]['RestartCount']
        passed('All four TLS service containers retained their start time and restart count')
        check_script = str(Path(__file__).with_name('rotate-mtls-certificate.py'))
        for days, expected_code in [(30,0),(100,2),(800,2)]:
            result = subprocess.run(['python3',check_script,'--manifest',str(workspace/'rotation.json'),'--identity','gateway','--check-expiry','--renew-before-days',str(days)],capture_output=True)
            assert result.returncode == expected_code
            if days == 800: assert json.loads(result.stdout)['authorityRenewalRequired'] is True
        passed('Renewal monitoring distinguishes healthy lifetime from a renewal due threshold')
    except Exception as exception:
        report['checks'].append({'name':'Rotation scenario','status':'failed','exception':type(exception).__name__,'detail':str(exception) if isinstance(exception,(AssertionError,ValueError,RuntimeError)) else 'See the private execution log'})
    finally:
        stop.set();worker.join(timeout=15)
    assert not worker.is_alive()
    if report['traffic']['failures']:
        report['checks'].append({'name':'Continuous protected traffic','status':'failed'})
    else: passed('Continuous protected HTTPS and internal identity traffic had no failed request during rotation/rollback')
    # Failure injection is separate from the uninterrupted rotation sample.
    docker('pause',project+'-auth-service-1')
    try:
        assert request('/api/user')[0] == 503
        assert adapter()[0] == 503
        assert adapter('appointments-service')[0] == 503
    finally:
        docker('unpause',project+'-auth-service-1')
    assert request('/api/user')[0] == 200
    passed('Rotated Auth timeout fails closed with 503 in Gateway and both real remote adapters')
    # This separate lifecycle test starts only after the no-interruption rotation sample ends.
    for identity in ['database','auth-service','gateway','clients-service','appointments-service']:
        docker('restart',project+'-'+identity+'-1')
    for attempt in range(40):
        try:
            status, body = request('/api/user')
            if status == 200:
                assert str(json.loads(body)['id']) == subject
                break
        except (urllib.error.URLError,TimeoutError):
            pass
        time.sleep(.25)
    else:
        raise AssertionError('The HTTPS session did not recover after the separate container lifecycle test')
    passed('HTTPS session and rotated TLS releases survive a separate full stack restart')
    assert request('/logout','POST',csrf=True)[0] == 204
    assert request('/api/user')[0] == 401
    passed('Session remains usable across rotation and is invalidated by logout afterwards')
    report['passed'] = sum(check['status']=='passed' for check in report['checks'])
    report['failed'] = sum(check['status']=='failed' for check in report['checks'])
    (workspace/'rotation-report.json').write_text(json.dumps(report,indent=2))
    print(json.dumps({'passed':report['passed'],'failed':report['failed'],'traffic':report['traffic']}))
    return report['failed']


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--workspace',required=True,type=Path)
    parser.add_argument('--accounts',required=True,type=Path)
    arguments = parser.parse_args()
    raise SystemExit(1 if run(arguments.workspace,arguments.accounts) else 0)
